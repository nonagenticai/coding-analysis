def _old_poetry_show_parse(stdout: str) -> list[dict[str, str]]:
    """The removed in-script parser of ``poetry show`` output, verbatim."""
    deps = []
    for line in stdout.strip().split("\n"):
        if line.strip():
            parts = line.split()
            if len(parts) >= 2:
                deps.append({"name": parts[0], "version": parts[1]})
    return deps


@pytest.fixture
def hostile_repo(tmp_path: Path) -> SimpleNamespace:
    """A repo whose root shadows ``pip`` and ``base64``; importing either drops a marker."""
    repo = tmp_path / "workspace"
    repo.mkdir()
    markers = tmp_path / "markers"
    markers.mkdir()
    scratch = tmp_path / "tmp"
    scratch.mkdir()
    for module in ("pip", "base64"):
        # Builtins only: an import here could itself pull in a shadowed module.
        (repo / f"{module}.py").write_text(
            f"open({str(markers / module)!r}, 'w').write('repo code ran')\n"
            f"raise RuntimeError('repo-root {module}.py executed')\n"
        )
    (repo / "requirements.txt").write_text("zz-req-only==1.0.0\n")
    (repo / "poetry.lock").write_text(
        '[[package]]\nname = "zz-poetry-only"\nversion = "9.9.9"\nfiles = []\n'
    )
    (repo / "app.py").write_text("import os\nfrom json import dumps\n")
    return SimpleNamespace(repo=repo, markers=markers, scratch=scratch)


def _fired(markers: Path) -> list[str]:
    return sorted(p.name for p in markers.iterdir())


class _LocalExec:
    """Stand-in for coding-containers ``/exec`` that runs the argv locally.

    ``/workspace`` maps to the fixture repo and ``/tmp/`` to a scratch dir.
    ``force_cwd_repo`` ignores the requested workdir (disables the cwd layer);
    ``strip_isolation`` drops leading ``-I``/``-P`` (disables the flag layer).
    """

    def __init__(self, fx: SimpleNamespace, *, force_cwd_repo=False, strip_isolation=False):
        self.fx = fx
        self.force_cwd_repo = force_cwd_repo
        self.strip_isolation = strip_isolation
        self.calls: list[tuple[list[str], str]] = []

    def _map(self, arg: str) -> str:
        return arg.replace("/tmp/", f"{self.fx.scratch}/").replace(
            file_discovery.WORKSPACE_ROOT, str(self.fx.repo)
        )

    async def execute(self, container_name, command, workdir, timeout, tenant_id):
        argv = shlex.split(command)
        self.calls.append((list(argv), workdir))
        if argv[0] == "python3":
            argv[0] = sys.executable
            if self.strip_isolation:
                while len(argv) > 1 and argv[1] in ("-I", "-P"):
                    del argv[1]
        argv = [argv[0], *(self._map(a) for a in argv[1:])]
        if self.force_cwd_repo:
            cwd = str(self.fx.repo)
        else:
            cwd = self._map(workdir) if workdir != "/" else "/"
        proc = subprocess.run(argv, cwd=cwd, capture_output=True, text=True, timeout=120)
        return {"exit_code": proc.returncode, "stdout": proc.stdout, "stderr": proc.stderr}


def _patched(fx: SimpleNamespace, **kw):
    exe = _LocalExec(fx, **kw)
    manager = SimpleNamespace(
        list_containers=AsyncMock(
            return_value=[SimpleNamespace(container_name="ws", status="running")]
        )
    )
    patches = [
        patch(f"{_FD}.get_container_manager", return_value=manager),
        patch(f"{_FD}.get_coding_containers_client", return_value=exe),
        # Non-Python manifests are read with find/cat, not an interpreter.
        patch(f"{_CORE}.scan_dependencies_multilang", AsyncMock(return_value=[])),
    ]
    for p in patches:
        p.start()
    return exe, patches


async def _run_full_python_scan(fx: SimpleNamespace, **kw) -> tuple[_LocalExec, dict, dict, dict]:
    exe, patches = _patched(fx, **kw)
    try:
        deps = await scanner_core.scan_dependencies("ws", tenant_id="t1")
        imports = await scanner_core._scan_python_imports("ws", ["app.py"], tenant_id="t1")
        validation = await scanner_core._validate_python_code("ws", None, tenant_id="t1")
    finally:
        for p in patches:
            p.stop()
    return exe, deps, imports, validation


class TestAutoIndexRunsNoRepoCode:
    async def test_full_scan_python_path_runs_no_repo_code_and_still_reports(self, hostile_repo):
        exe, deps, imports, validation = await _run_full_python_scan(hostile_repo)

        assert _fired(hostile_repo.markers) == []
        by_name = {d.name: d for d in deps["dependencies"]}
        assert "error" not in deps, deps.get("error")
        assert by_name["pip"].source == "pip"  # pip list ran and was parsed
        assert (by_name["zz-poetry-only"].version, by_name["zz-poetry-only"].source) == (
            "9.9.9",
            "poetry",
        )
        assert (by_name["zz-req-only"].version, by_name["zz-req-only"].source) == (
            "1.0.0",
            "requirements",
        )
        # Relative targets still resolve against the repo and report as given.
        assert {i.module for i in imports["imports"]} == {"os", "json"}
        assert {i.file_path for i in imports["imports"]} == {"app.py"}
        assert validation["valid_files"] >= 1
        # Every interpreter the scan started was isolated and ran from "/".
        py_calls = [(a, w) for a, w in exe.calls if a[0] == "python3"]
        assert len(py_calls) == 6  # write+run for deps, imports, validation
        for argv, workdir in py_calls:
            assert argv[:3] == ["python3", "-I", "-P"], argv[:4]
            assert workdir == "/"

    async def test_isolation_flags_alone_block_shadowing(self, hostile_repo):
        """cwd layer disabled (every exec runs IN the repo): -I -P must hold alone."""
        _, deps, _, _ = await _run_full_python_scan(hostile_repo, force_cwd_repo=True)
        assert _fired(hostile_repo.markers) == []
        assert deps["dependency_count"] > 0

    async def test_neutral_cwd_alone_blocks_shadowing(self, hostile_repo):
        """Flag layer disabled (plain python3): cwd "/" must hold alone."""
        _, deps, _, _ = await _run_full_python_scan(hostile_repo, strip_isolation=True)
        assert _fired(hostile_repo.markers) == []
        assert deps["dependency_count"] > 0

    async def test_control_both_layers_off_repo_code_runs(self, hostile_repo):
        """Positive control: the fixture really does fire when nothing protects it."""
        await _run_full_python_scan(hostile_repo, force_cwd_repo=True, strip_isolation=True)
        assert "base64" in _fired(hostile_repo.markers)


class TestInnerPipSubprocess:
    """The script's own ``pip list`` child: flags are not inherited, so it has both layers."""

    FLAGS = '"-I", "-P", '
    CWD = 'cwd="/",'

    def _run_script(self, fx: SimpleNamespace, script: str) -> subprocess.CompletedProcess:
        path = fx.scratch / "scan_dependencies.py"
        path.write_text(script)
        # Outer interpreter deliberately unprotected and in the repo, so only
        # the inner child's own layers are under test.
        return subprocess.run(
            [sys.executable, str(path), str(fx.repo)],
            cwd=fx.repo,
            capture_output=True,
            text=True,
            timeout=120,
        )

    @pytest.mark.parametrize("drop", ["", "FLAGS", "CWD"])
    def test_pip_child_never_imports_repo_pip(self, hostile_repo, drop):
        script = dependency_scan_script.DEPENDENCY_SCAN_SCRIPT
        assert self.FLAGS in script and self.CWD in script
        if drop:
            script = script.replace(getattr(self, drop), "")
        proc = self._run_script(hostile_repo, script)
        assert proc.returncode == 0, proc.stderr
        assert _fired(hostile_repo.markers) == []
        assert '"source": "pip"' in proc.stdout

    def test_control_both_dropped_repo_pip_runs(self, hostile_repo):
        script = dependency_scan_script.DEPENDENCY_SCAN_SCRIPT
        script = script.replace(self.FLAGS, "").replace(self.CWD, "")
        self._run_script(hostile_repo, script)
        assert _fired(hostile_repo.markers) == ["pip"]


class TestPoetryLockReplacesPoetryShow:
    def _parse(self, text: str) -> list[dict[str, str]]:
        ns: dict[str, Any] = {"__name__": "not_main"}
        exec(compile(dependency_scan_script.DEPENDENCY_SCAN_SCRIPT, "<scan>", "exec"), ns)
        return ns["parse_poetry_lock"](text)

    def test_lock_parse_matches_poetry_show_shape(self):
        parsed = self._parse(_POETRY_LOCK)
        shown = _old_poetry_show_parse(_POETRY_SHOW_NOT_INSTALLED.replace(" (!) ", " "))
        assert parsed == shown
        assert all(set(d) == {"name", "version"} for d in parsed)

    def test_old_parser_took_not_installed_marker_as_version(self):
        """Why the lock is also more correct: in the pod nothing is installed."""
        old = _old_poetry_show_parse(_POETRY_SHOW_NOT_INSTALLED)
        assert {d["version"] for d in old} == {"(!)"}

    def test_no_lock_or_bad_lock_yields_nothing(self, tmp_path):
        ns: dict[str, Any] = {"__name__": "not_main"}
        exec(compile(dependency_scan_script.DEPENDENCY_SCAN_SCRIPT, "<scan>", "exec"), ns)
        assert ns["get_poetry_dependencies"](tmp_path) == []
        (tmp_path / "poetry.lock").write_text("not = [valid toml")
        assert ns["get_poetry_dependencies"](tmp_path) == []

    def test_script_starts_no_process_but_pip(self):
        """poetry is never executed: pip list is the script's ONLY child process."""
        script = dependency_scan_script.DEPENDENCY_SCAN_SCRIPT
        assert script.count("subprocess.") == 1
        assert '"-m", "pip", "list"' in script
