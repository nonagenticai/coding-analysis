"""Auto-index must never execute code from the imported repository (coding-analysis#104).

Auto-index runs ``full_scan`` against a freshly imported, untrusted repo in the
tenant's workspace pod. Python puts the cwd (``-c`` / ``-m``) or the script dir
on ``sys.path``, so with cwd ``/workspace`` a repo-root ``pip.py`` or
``base64.py`` shadowed the real module and ran with no user action.

These tests run the REAL command-construction code and execute the resulting
argv in a REAL local subprocess, with ``/workspace`` mapped to a fixture repo
whose root holds ``pip.py`` / ``base64.py`` that drop a marker file on import.

Two independent layers stop the shadowing: the ``-I -P`` interpreter flags and
the neutral cwd ``/``. Each is proven alone (the other disabled by the fake
executor), and a positive control disables both and requires the marker to
appear, so a fixture that could never fire cannot pass silently.
"""

